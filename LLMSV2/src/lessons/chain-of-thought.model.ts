/**
 * The word problem behind the chain-of-thought lab. The arithmetic is real:
 * every step reads the number on the line above and computes from it, so a
 * corrupted line flows through to the final answer by ordinary calculation.
 */

export const PROBLEM =
  'A café sells 48 coffees a day at $3 each. It is open 6 days a week. Its costs are $500 a week. ' +
  'The profit is split equally between 2 owners. How many dollars does each owner get per week?';

export const DIRECT_SUFFIX = 'Give only the final number.';
export const CHAIN_SUFFIX = 'Work it out step by step, then give the answer.';

export interface StepDef {
  name: string;
  /** Operand taken from the problem text. */
  operand: number;
  sym: '×' | '−' | '÷';
  apply: (prev: number) => number;
  /** What an injected slip adds to the correct result of this step. */
  slip: number;
}

export const START = 48;
export const STEPS: StepDef[] = [
  { name: 'Daily sales', operand: 3, sym: '×', apply: (x) => x * 3, slip: -10 },
  { name: 'Weekly sales', operand: 6, sym: '×', apply: (x) => x * 6, slip: -18 },
  { name: 'Weekly profit', operand: 500, sym: '−', apply: (x) => x - 500, slip: 100 },
  { name: 'Each owner', operand: 2, sym: '÷', apply: (x) => x / 2, slip: 0 },
];

export interface Line {
  name: string;
  input: number; // read from the problem (step 1) or from the line above
  operand: number;
  sym: string;
  result: number; // what is written
  truth: number; // what a clean chain would have written here
  slipped: boolean; // this is the line where the error was injected
  tainted: boolean; // result differs from the clean chain
  text: string;
}

/** Runs the chain. `errAt` is the index of the step whose written result is corrupted, or -1. */
export function runChain(errAt: number): Line[] {
  const lines: Line[] = [];
  let prev = START;
  let clean = START;
  STEPS.forEach((s, i) => {
    const truth = s.apply(clean);
    const result = s.apply(prev) + (i === errAt ? s.slip : 0);
    lines.push({
      name: s.name, input: prev, operand: s.operand, sym: s.sym, result, truth,
      slipped: i === errAt, tainted: result !== truth,
      text: `${s.name}: ${prev} ${s.sym} ${s.operand} = ${result}`,
    });
    prev = result;
    clean = truth;
  });
  return lines;
}

export const ANSWER = runChain(-1)[STEPS.length - 1].result;
export const answerLine = (n: number) => `Answer: ${n}`;

/** Text generated by the chain lane after `written` steps (the answer line follows the last step). */
export function chainOutput(lines: Line[], written: number): string {
  const body = lines.slice(0, written).map((l) => l.text).join('\n');
  return written === lines.length ? body + '\n' + answerLine(lines[lines.length - 1].result) : body;
}

